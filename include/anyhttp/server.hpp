/// What a \ref Server is made with.
struct Config
{
   /// The address to listen on, for TCP and for HTTP/3 alike.
   std::string listen_address = "::";

   /// The port to listen on, for TCP and for HTTP/3 alike. Zero has the kernel pick one, see
   /// \ref Server::local_endpoint.
   uint16_t port = 8080;

   /// Give every connection a strand of its own, for a server whose context runs on several
   /// threads. The handler of a request then runs on the strand of its connection.
   bool use_strand = false;

   /**
    * Bind the TCP acceptor and the HTTP/3 UDP socket with SO_REUSEPORT, so that several servers,
    * each on an executor of its own, can listen on the same port and the kernel spreads the load
    * over them: new TCP connections, and UDP datagrams by their address and port. A QUIC
    * connection whose client address changes (migration, NAT rebinding) lands on another server
    * then, which does not know it. All of them have to be bound before traffic arrives -- each one
    * that joins reshuffles where the datagrams go.
    */
   bool reuse_port = false;

   /**
    * The kernel's send and receive buffer, in bytes, for every TCP connection the server accepts;
    * zero (the default) leaves the kernel's autotuning alone, which grows them into the megabytes.
    * TCP only -- HTTP/3 has its own flow control, and the UDP socket is shared by every connection
    * on it.
    *
    * This is a testing aid, not a tuning knob: pinning them small bounds how much a peer can write
    * before it has to wait, which is the only way to make a write block at a predictable point
    * over HTTP/1.1, where there is no flow control of its own. Small buffers cost throughput --
    * 8 KiB of receive buffer makes the 'PostRange' tests very slow -- so leave them at zero
    * unless a test needs the back pressure.
    */
   int socket_send_buffer_size = 0;

   /// See \ref socket_send_buffer_size.
   int socket_receive_buffer_size = 0;

   /**
    * The server's certificate chain, and with \ref tls_private_key its key, as PEM files, for TLS
    * over TCP and for HTTP/3. The chain starts with the server certificate, followed by its
    * intermediates. Both files are read when the Server is constructed, which fails if they can't
    * be, and not again: replacing them on disk takes effect with the next Server. Relative paths
    * are resolved against the working directory.
    *
    * The defaults are the test PKI generated by the 'pki' target (see cmake/pki.cmake) -- good
    * for development and the tests, and for nothing else.
    */
   std::string tls_certificate_chain = "pki/out/server-chain.pem";

   /// The private key that goes with \ref tls_certificate_chain, read at the same time.
   std::string tls_private_key = "pki/out/server-key.pem";

   /**
    * The largest header section of a request the server accepts, in bytes. A request with more is
    * answered with 431 (Request Header Fields Too Large) and never reaches the request handler.
    * HTTP/1.1 counts the request line and header lines as received, and closes the connection
    * after the 431 response. HTTP/2 and HTTP/3 count each field as its name and value plus 32
    * bytes (pseudo-headers included) and announce the limit to the client in their SETTINGS.
    *
    * Fields beyond the limit are not stored, so this bounds the memory a request can take up with
    * its headers. A single field is also limited by the protocol libraries: 64 KiB for HTTP/2 and
    * HTTP/3, where a larger one fails the whole connection. So does an HTTP/2 header block that
    * takes up more CONTINUATION frames than a header section of this size needs (but at least 8).
    */
   size_t max_header_size = default_max_header_size;

   /**
    * How many requests a client may have in progress at once on one connection, announced to it as
    * SETTINGS_MAX_CONCURRENT_STREAMS over HTTP/2 and as the limit on bidirectional streams over
    * HTTP/3. A client that has reached it is refused the next request rather than kept waiting for
    * a stream: Session::async_submit() fails with \c would_block, the way HTTP/1.1 does with its
    * limit of one, see the page on concurrent requests.
    *
    * HTTP/1.1 has no use for this: one request at a time is what the protocol gives it.
    */
   uint64_t max_concurrent_streams = 100;

   /**
    * How long a client may remember the HTTP/3 endpoint this server advertises in every response
    * it sends over HTTP/1.1 and HTTP/2, as <tt>Alt-Svc: h3=":8080"; ma=86400</tt> (RFC 7838).
    * A client that takes it up makes its *next* connection over QUIC -- there is no in-band
    * upgrade to HTTP/3, so this is the whole of it. HTTP/3 shares the endpoint the TCP acceptor
    * is listening on, so what is advertised is the port and nothing else: the same host, over
    * QUIC. Zero sends no "Alt-Svc" at all.
    *
    * Advertising over cleartext HTTP is of no use to browsers and curl, which honour "Alt-Svc"
    * for HTTPS origins only -- the alternative has to be at least as secure as the origin.
    */
   std::chrono::seconds alt_svc_max_age = std::chrono::hours{24};

   /**
    * HTTP/3 only: how long a QUIC connection may go without a packet from its peer before it is
    * dropped. This is the only way a peer that vanished without a CONNECTION_CLOSE -- a killed
    * client, a machine that went to sleep -- is ever noticed, so it also bounds how long its
    * session and streams stay around. 30s is what the ngtcp2 examples use.
    */
   std::chrono::nanoseconds idle_timeout = std::chrono::seconds{30};

   /**
    * HTTP/3 only, testing aid: probability (0.0 ... 1.0) with which an individual QUIC datagram
    * is thrown away instead of being processed (rx) or actually sent (tx). This exercises loss
    * recovery -- retransmits, PTO, ACK handling -- without needing a lossy network. Dropping
    * happens per QUIC packet, i.e. GRO-coalesced datagrams are dropped individually and TX
    * GSO batching is bypassed while \c drop_rate_tx is non-zero.
    */
   double drop_rate_rx = 0.0;

   /// See \ref drop_rate_rx.
   double drop_rate_tx = 0.0;

   /**
    * HTTP/3 only, for benchmarking: turn off the kernel's UDP offloads. Without GRO, every received
    * datagram costs a recvmsg() of its own; without GSO, every QUIC packet costs a sendto() of its
    * own instead of a whole same-sized run going out in one sendmsg().
    */
   bool disable_gro = false;

   /// See \ref disable_gro.
   bool disable_gso = false;
};

