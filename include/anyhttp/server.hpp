/// What serves a request, see \ref Server::on_request.
using RequestHandler = std::function<Task<void>(Request, Response)>;

/**
 * Listens on a port, TCP and UDP both, and serves every protocol on it: HTTP/1.1 and HTTP/2, with
 * or without TLS, told apart by what the client sends first, and HTTP/3 over UDP.
 *
 * It starts listening when it is made, and stops when it is destroyed, which also ends every
 * connection it has. It can be moved but not copied.
 */
class Server
{
public:
   /// \cond internal
   class Impl;
   Server(Server&& other) noexcept;
   Server& operator=(Server&& other) noexcept;
   ~Server();
   /// \endcond

   /// Starts listening.
   /// \param executor What the server and its connections run on.
   /// \param config Where it listens, and how it serves.
   /// \throws std::exception for a certificate that can't be read or a port that is taken.
   Server(Executor executor, Config config);

   /// The executor type, for what looks for one.
   using executor_type = Executor;

   /// \return The executor the server runs on.
   executor_type get_executor() const noexcept;

   /// Sets what serves the requests from now on, each in a coroutine of its own on the executor of
   /// its connection. Set it before the first request comes in, as requests go unserved without.
   /// \param handler What serves a request.
   void on_request(RequestHandler&& handler);

   /**
    * Serves plain QUIC streams (see \ref quic::Stream) to clients that negotiate \c config.alpn,
    * on the UDP port HTTP/3 is on: each such connection is handed to \p handler, on its own
    * executor, and closed when the handler returns. Registering an ALPN again replaces what was
    * registered for it, from the next connection on.
    *
    * Of \p config, the server uses the flow control limits, the error codes and the write mode;
    * its idle timeout is Config::idle_timeout.
    *
    * \param config The protocol, and how to serve it.
    * \param handler What each connection is handed to.
    */
   void on_quic(quic::Config config, quic::ConnectionHandler handler);

   /// \return Where the server listens, with the actual port if \ref Config::port was zero.
   TcpEndpoint local_endpoint() const;

private:
   std::shared_ptr<Impl> impl;
};

